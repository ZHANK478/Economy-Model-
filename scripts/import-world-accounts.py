"""Generate scenario observations from three downloaded World Bank v2 API responses.

Inputs: country metadata, NY.GDP.MKTP.CD (2000), SP.POP.TOTL (2000–2024).
Use source 2 (World Development Indicators) and all returned pages.
"""
import json
from pathlib import Path
import sys


def rows(path):
    metadata, records = json.loads(Path(path).read_text())
    assert metadata["pages"] == 1
    return records


if __name__ == "__main__":
    countries_file, gdp_file, population_file = sys.argv[1:]
    countries = {r["id"] for r in rows(countries_file) if r["region"]["id"] != "NA"}
    gdp = {r["countryiso3code"]: round(r["value"] / 1e6, 3)
           for r in rows(gdp_file) if r["value"] is not None}
    population = {(r["countryiso3code"], int(r["date"])): r["value"]
                  for r in rows(population_file)}
    years = range(2000, 2025)
    tracked = """WLD GBR USA CAN RUS CHN JPN IND AUS ZAF IRN
                 AUT BEL DNK FIN FRA DEU GRC IRL ITA LUX NLD PRT ESP SWE""".split()
    series = {code: [population[code, year] for year in years] for code in tracked}
    assert all(min(values) > 0 for values in series.values())
    opening = {code: gdp[code] for code in sorted((countries & gdp.keys()) | {"WLD"})}
    assert set(tracked) <= opening.keys()
    print("// Generated by scripts/import-world-accounts.py from World Bank WDI, 2026-11-11 release.")
    print("// GDP is measured in millions of current 2000 USD. Population is measured in people.")
    print("export const WDI_GDP_2000 = " + json.dumps(opening, separators=(",", ":")) + ";")
    print("export const WDI_POPULATION_2000_2024 = {")
    for code, values in series.items():
        print(f"  {code}: {json.dumps(values, separators=(',', ':'))},")
    print("};")
