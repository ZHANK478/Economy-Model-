"""Extract UK territorial profiles. Input names and editions are in docs/uk-regions.md."""

import csv
import json
import re
import sys
from pathlib import Path
from xml.etree import ElementTree
from zipfile import ZipFile

from openpyxl import load_workbook
import xlrd


# ITL1, ONS geography code, MYE 2001 name, LFS activity/unemployment series,
# PESA name, published urban share (using each administration's classification).
REGIONS = [
    ('TLC', 'E12000001', 'NORTH EAST', 'YCHP', 'YCMP', 'North East', .82),
    ('TLD', 'E12000002', 'NORTH WEST', 'YCHQ', 'YCMQ', 'North West', .88),
    ('TLE', 'E12000003', 'YORKSHIRE AND THE HUMBER', 'YCHR', 'YCMR', 'Yorkshire and Humberside', .80),
    ('TLF', 'E12000004', 'EAST MIDLANDS', 'YCHS', 'YCMS', 'East Midlands', .71),
    ('TLG', 'E12000005', 'WEST MIDLANDS', 'YCHT', 'YCMT', 'West Midlands', .84),
    ('TLH', 'E12000006', 'EAST OF ENGLAND', 'YCHU', 'YCMU', 'Eastern', .69),
    ('TLI', 'E12000007', 'LONDON', 'YCHV', 'YCMV', 'London', 1.0),
    ('TLJ', 'E12000008', 'SOUTH EAST', 'YCHW', 'YCMW', 'South East', .78),
    ('TLK', 'E12000009', 'SOUTH WEST', 'YCHX', 'YCMX', 'South West', .66),
    ('TLL', 'W92000004', 'WALES', 'YCHZ', 'YCMZ', 'Wales', .65),
    ('TLM', 'S92000003', 'SCOTLAND', 'YCIA', 'YCNA', 'Scotland', .688),
    ('TLN', 'N92000002', 'NORTHERN IRELAND', 'LZKN', 'ZSFA', 'Northern Ireland', .625),
]


def read_ages(folder):
    with ZipFile(folder / 'mid2001.zip') as archive:
        raw = archive.read('mid-2001-unformatted-data-file.xls')
    sheet = xlrd.open_workbook(file_contents=raw).sheet_by_name('Mid-2001 Persons')
    return {row[1]: (int(row[2]), [int(sum(row[3:21])), int(sum(row[21:68])),
                                   int(sum(row[68:94]))], int(sum(row[3:8])))
            for row in (sheet.row_values(i) for i in range(1, 17))}


def read_labor(folder):
    with (folder / 'lms.csv').open(encoding='utf-8-sig', newline='') as stream:
        rows = csv.reader(stream)
        next(rows)
        series = next(rows)
        year = next(row for row in rows if row[0] == '2000')
    return dict(zip(series, year))


def read_pesa(folder):
    text = (folder / 'pesa-2005.txt').read_text()
    start = text.index('Table 8.11        UK Identifiable expenditure on services by function')
    year = text.index('2000–01\n', start)
    block = text[year:text.index('UK identifiable expenditure',year)]
    result = {}
    for line in block.splitlines():
        cols = re.split(r' {2,}', line.strip())
        if len(cols) == 17:
            values = [int(cols[i+1].replace(',', '')) for i in (11, 13, 8, 10, 14, 15)]
            result[cols[0]] = dict(zip(('health','education','transport','housing','social','total'),values))
    return result


def read_roads(folder):
    table_ns = '{urn:oasis:names:tc:opendocument:xmlns:table:1.0}'
    with ZipFile(folder / 'roads.ods') as archive:
        content = ElementTree.fromstring(archive.read('content.xml'))
    table = next(t for t in content.iter(table_ns+'table')
                 if t.get(table_ns+'name') == 'RDL0201_(2005)')
    result = {'N92000002':24728}
    for row in table.findall(table_ns+'table-row')[9:21]:
        cols = [''.join(cell.itertext()).strip() for cell in row]
        result[cols[0]] = int(cols[24].replace(',', ''))
    return result


def profiles(folder):
    age = read_ages(folder)
    labor = read_labor(folder)
    public_spending = read_pesa(folder)
    roads = read_roads(folder)
    w = load_workbook(folder / 'mye25.xlsx', read_only=True, data_only=True)
    area = {code: value for code, _, _, value in w['MYE5'].iter_rows(min_row=9,max_col=4,values_only=True)}
    for code, geo, name, active, unemployed, public_name, urban in REGIONS:
        people, cohorts, preschool = age[name]
        assert sum(cohorts) == people and 0 < float(labor[unemployed]) < float(labor[active])
        yield code, {
            'age': [round(n/people, 9) for n in cohorts],
            'preschoolShare': round(preschool/cohorts[0], 9),
            'laborForce': round(float(labor[active])*1000/people, 9),
            'unemployed': round(float(labor[unemployed])*1000/people, 9),
            'unemploymentRateObserved': round(float(labor[unemployed])/float(labor[active]), 6),
            'urbanShare': urban,
            'landKm2': area[geo],
            'roadsKm': roads[geo],
            'roadsYear': 2001 if code == 'TLN' else 2005,
            'spending': public_spending[public_name],
        }


if __name__ == '__main__':
    print('// Generated by scripts/import-uk-regional-profiles.py. See docs/uk-regions.md.')
    print('export const UK_REGIONAL_PROFILES = {')
    for code, row in profiles(Path(sys.argv[1])):
        print(f'  {code}: '+json.dumps(row,separators=(',',':'))+',')
    print('};')
