"""Regenerate the 2000 UK calibration from the ONS workbooks in docs/uk-regions.md."""

from collections import defaultdict
import json
from pathlib import Path
import sys

from openpyxl import load_workbook
import xlrd


# ITL1 code, population workbook label, map label, local authority, JOBS05 sheet.
REGIONS = [
    ('TLC', 'North East', 'Ньюкасл-апон-Тайн', 'E08000021', 1),
    ('TLD', 'North West', 'Манчестер', 'E08000003', 2),
    ('TLE', 'Yorkshire and The Humber', 'Лидс', 'E08000035', 3),
    ('TLF', 'East Midlands', 'Ноттингем', 'E06000018', 4),
    ('TLG', 'West Midlands', 'Бирмингем', 'E08000025', 5),
    ('TLH', 'East', 'Саутенд-он-Си', 'E06000033', 6),
    ('TLI', 'London', 'Лондон', 'TLI', 7),
    ('TLJ', 'South East', 'Брайтон', 'E06000043', 8),
    ('TLK', 'South West', 'Бристоль', 'E06000023', 9),
    ('TLL', 'Wales', 'Кардифф', 'W06000015', 11),
    ('TLM', 'Scotland', 'Глазго', 'S12000049', 12),
    ('TLN', 'Northern Ireland', 'Белфаст', 'N09000003', 13),
]
SECTOR_GVA = [
    ('A (1-3)',), ('B (5-9)', 'D (35)', 'E (36-39)'),
    ('C (10-33)',), ('F (41-43)',), ('G-T',),
]
SECTOR_JOBS = [('A',), ('B', 'D', 'E'), ('C',), ('F',), ('G-T',)]


def region_gva(sheet):
    return {
        (code, sic): (name, base, year)
        for code, name, sic, _, base, _, year in sheet.iter_rows(
            min_row=3, max_col=7, values_only=True
        )
    }


def region_jobs(sheet):
    columns = {label: i for i, label in enumerate(sheet.row_values(5))}
    rows = [sheet.row_values(i) for i in range(6, sheet.nrows)
            if str(sheet.cell_value(i, 0)).strip() in ('Mar 00', 'Jun 00', 'Sep 00', 'Dec 00')]
    if len(rows) != 4:
        raise ValueError(f'{sheet.name}: expected four quarters in 2000')
    return [int(250 * sum(row[columns[key]] for row in rows for key in codes))
            for codes in SECTOR_JOBS]


def read_calibration(folder):
    gva = load_workbook(folder / 'gva.xlsx', read_only=True, data_only=True)
    nominal, volume = (region_gva(gva[name]) for name in ('Table 1c', 'Table 1a'))
    jobs = xlrd.open_workbook(str(folder / 'jobs.xls'), on_demand=True)
    income = load_workbook(folder / 'income.xlsx', read_only=True, data_only=True)
    regional_income = {code: y2000 for _, code, _, _, _, _, y2000 in income['Table 1'].iter_rows(
        min_row=5, max_col=7, values_only=True
    )}
    population = load_workbook(folder / 'population.xlsx', read_only=True, data_only=True)
    regional_population, city_population = defaultdict(int), {}
    for label, code, _, _, _, value in population.active.iter_rows(min_row=2, max_col=6, values_only=True):
        if not isinstance(value, int):
            continue
        regional_population[label.strip()] += value
        city_population[code] = value
    local = load_workbook(folder / 'city-gdp.xlsx', read_only=True, data_only=True)
    city_gva = {code: value for _, code, _, _, _, value in local['Table 1'].iter_rows(
        min_row=3, max_col=6, values_only=True
    )}
    result = []
    for code, label, map_name, city, jobs_sheet in REGIONS:
        name, _, total_gva = nominal[code, 'Total']
        _, volume_1998, volume_2000 = volume[code, 'Total']
        residents = regional_population[label]
        gva_sectors = [sum(nominal[code, key][2] for key in keys) for keys in SECTOR_GVA]
        city_residents = residents if city == code else city_population[city]
        city_value_added = total_gva if city == code else city_gva[city]
        assert 0 < city_residents <= residents and 0 < city_value_added <= total_gva
        result.append({
            'id': code, 'name': name.strip(), 'population': residents,
            'workforceJobs': region_jobs(jobs.sheet_by_index(jobs_sheet)),
            'gvaMillionGBP': total_gva, 'sectorGvaMillionGBP': gva_sectors,
            'disposableIncomeMillionGBP': regional_income[code],
            'financeGvaMillionGBP': nominal[code, 'K (64-66)'][2],
            'realGvaGrowth1998To2000': round(volume_2000 / volume_1998 - 1, 6),
            'city': {'id': city, 'name': map_name, 'population': city_residents,
                     'gvaMillionGBP': city_value_added},
        })
    edinburgh = 'S12000036'
    extra_city = {
        'id': edinburgh, 'regionId': 'TLM', 'name': 'Эдинбург',
        'population': city_population[edinburgh], 'gvaMillionGBP': city_gva[edinburgh],
    }
    return result, extra_city


if __name__ == '__main__':
    rows, edinburgh = read_calibration(Path(sys.argv[1]))
    print('// Generated by scripts/import-uk-regional-calibration.py. See docs/uk-regions.md.')
    print('export const UK_REGIONS_2000 = [')
    for row in rows:
        print('  ' + json.dumps(row, ensure_ascii=False, separators=(',', ':')) + ',')
    print('];')
    print('export const EDINBURGH_2000 = ' + json.dumps(edinburgh, ensure_ascii=False, separators=(',', ':')) + ';')
